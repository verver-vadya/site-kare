// Самая низкая цена группы для подписи «от … ₽»
export const groupFrom = (g: Group) =>
  Math.min(...g.services.filter((s) => !s.free && !s.addon).map((s) => (Array.isArray(s.prices) ? s.prices[0] : s.prices)));

export const allServices = groups.flatMap((g) => g.services.map((s) => ({ ...s, group: g.slug, groupName: g.name })));
export const serviceById = (id: string) => allServices.find((s) => s.id === id);
